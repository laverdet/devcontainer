#!/bin/sh
# timezone Feature: install script.
#
# Runs once, as root, while the dev container image is built. The host is not
# reachable from here, so this only installs the entrypoint, optionally makes
# sure tzdata is present, and records the Feature options for the entrypoint.
set -eu

FEATURE_DIR=$(cd "$(dirname "$0")" && pwd)
SHARE=/usr/local/share/devcontainer-timezone
ZONEINFO=/usr/share/zoneinfo

# Feature options arrive as upper-cased environment variables.
TIMEZONE=${TIMEZONE:-}
INSTALLTZDATA=${INSTALLTZDATA:-true}

valid_zone_name() {
	case $1 in
		'' | /* | */ | *//* | *..* | .* | *[!A-Za-z0-9_+./-]*) return 1 ;;
	esac
	return 0
}

if [ -n "$TIMEZONE" ] && ! valid_zone_name "$TIMEZONE"; then
	echo "timezone: option 'timezone' does not look like an IANA zone name: '$TIMEZONE'" >&2
	exit 1
fi
case $INSTALLTZDATA in
	true | false) ;;
	*)
		echo "timezone: option 'installTzdata' must be true or false, got '$INSTALLTZDATA'" >&2
		exit 1
		;;
esac

have_zoneinfo() {
	[ -f "$ZONEINFO/zone1970.tab" ] || [ -d "$ZONEINFO/America" ]
}

install_tzdata() {
	if command -v apt-get >/dev/null 2>&1; then
		export DEBIAN_FRONTEND=noninteractive
		# Drop the package lists afterwards only if this script had to fetch them.
		had_lists=$(find /var/lib/apt/lists -maxdepth 1 -type f ! -name lock | head -n 1)
		apt-get update -y
		apt-get install -y --no-install-recommends tzdata
		[ -n "$had_lists" ] || rm -rf /var/lib/apt/lists/*
	elif command -v apk >/dev/null 2>&1; then
		apk add --no-cache tzdata
	elif command -v pacman >/dev/null 2>&1; then
		# Same rule: the sync databases and the package cache stay only if they were there.
		had_sync=$(find /var/lib/pacman/sync -maxdepth 1 -name '*.db' 2>/dev/null | head -n 1)
		had_pkgs=$(find /var/cache/pacman/pkg -maxdepth 1 -type f 2>/dev/null | head -n 1)
		pacman -Sy --noconfirm tzdata
		[ -n "$had_pkgs" ] || rm -rf /var/cache/pacman/pkg/*
		[ -n "$had_sync" ] || rm -rf /var/lib/pacman/sync/*
	else
		echo "timezone: no known package manager, not installing tzdata (the host's zone file will be copied in at start)" >&2
	fi
}

if [ "$INSTALLTZDATA" = true ] && ! have_zoneinfo; then
	echo "timezone: installing tzdata"
	install_tzdata || echo "timezone: warning: installing tzdata failed; continuing without it" >&2
fi

mkdir -p "$SHARE"
cp "$FEATURE_DIR/entrypoint.sh" "$SHARE/entrypoint"
chmod 0755 "$SHARE/entrypoint"

# Single-quote a value so the config file can be sourced safely.
sq() {
	printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"
}
{
	echo '# Generated by the timezone Feature at image build time; sourced by the entrypoint.'
	echo "TIMEZONE=$(sq "$TIMEZONE")"
} >"$SHARE/config"
chmod 0644 "$SHARE/config"

# A fixed zone can be applied right away, so the image is right even when it is
# run without the devcontainer CLI's entrypoint wrapper.
if [ -n "$TIMEZONE" ] && [ -f "$ZONEINFO/$TIMEZONE" ]; then
	ln -sfn "$ZONEINFO/$TIMEZONE" /etc/localtime
	printf '%s\n' "$TIMEZONE" >/etc/timezone
fi

echo "timezone: installed${TIMEZONE:+ (fixed zone $TIMEZONE)}"
