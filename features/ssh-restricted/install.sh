#!/bin/sh
set -eu

FEATURE_DIR=$(cd "$(dirname "$0")" && pwd)
SHARE=/usr/local/share/devcontainer-ssh-agent
SSH_CONF=/etc/ssh/ssh_config.d/devcontainer-ssh-restricted.conf

INSTALLOPENSSHCLIENT=${INSTALLOPENSSHCLIENT:-true}
IDENTITIES=${IDENTITIES:-}
case $INSTALLOPENSSHCLIENT in
	true | false) ;;
	*)
		echo "ssh-agent: option 'installOpenSSHClient' must be true or false, got '$INSTALLOPENSSHCLIENT'" >&2
		exit 1
		;;
esac

install_ssh() {
	if command -v apt-get >/dev/null 2>&1; then
		export DEBIAN_FRONTEND=noninteractive
		# Drop the package lists afterwards only if this script had to fetch them.
		had_lists=$(find /var/lib/apt/lists -maxdepth 1 -type f ! -name lock | head -n 1)
		apt-get update -y
		apt-get install -y --no-install-recommends openssh-client
		[ -n "$had_lists" ] || rm -rf /var/lib/apt/lists/*
	elif command -v apk >/dev/null 2>&1; then
		apk add --no-cache openssh-client
	elif command -v pacman >/dev/null 2>&1; then
		# Same rule: the sync databases and the package cache stay only if they were there.
		had_sync=$(find /var/lib/pacman/sync -maxdepth 1 -name '*.db' 2>/dev/null | head -n 1)
		had_pkgs=$(find /var/cache/pacman/pkg -maxdepth 1 -type f 2>/dev/null | head -n 1)
		pacman -Sy --noconfirm openssh
		[ -n "$had_pkgs" ] || rm -rf /var/cache/pacman/pkg/*
		[ -n "$had_sync" ] || rm -rf /var/lib/pacman/sync/*
	else
		echo "ssh-agent: no known package manager, not installing the OpenSSH client" >&2
	fi
}

if [ "$INSTALLOPENSSHCLIENT" = true ] && ! command -v ssh >/dev/null 2>&1; then
	echo "ssh-agent: installing the OpenSSH client"
	install_ssh || echo "ssh-agent: warning: installing the OpenSSH client failed; continuing without it" >&2
fi

mkdir -p "$SHARE"
cp "$FEATURE_DIR/check.sh" "$SHARE/check"
chmod 0755 "$SHARE/check"

# identities is "alias [user@]host key-type key-blob [comment], ..." and every entry becomes a Host
# block whose IdentityFile is just that public key: the private key stays on the host, in the
# restricted agent, which ssh asks to sign for any configured public key it holds. The file is
# system-wide so ~/.ssh/config, which may be a bind mount from the host, is never touched and still
# wins. Debian, Alpine and Arch all ship the Include for ssh_config.d.
write_identities() {
	[ -n "$1" ] || return 0
	mkdir -p "$SHARE/identities" "$(dirname "$SSH_CONF")"
	echo "# Generated by the devcontainer ssh-restricted Feature from its 'identities' option." >"$SSH_CONF"
	chmod 0644 "$SSH_CONF"
	aliases=
	while read -r alias target type blob comment; do
		[ -n "$alias" ] || continue
		case $alias in
			*[!A-Za-z0-9._-]*)
				echo "ssh-agent: identities: alias '$alias' may only contain letters, digits, '.', '_' and '-'" >&2
				exit 1
				;;
		esac
		if [ -z "$blob" ]; then
			echo "ssh-agent: identities: expected 'alias [user@]host key-type key-blob', got: $alias $target $type" >&2
			exit 1
		fi
		pub=$SHARE/identities/$alias.pub
		printf '%s %s%s\n' "$type" "$blob" "${comment:+ $comment}" >"$pub"
		chmod 0644 "$pub"
		{
			echo
			echo "Host $alias"
			printf '\tHostName %s\n' "${target#*@}"
			case $target in *@*) printf '\tUser %s\n' "${target%%@*}" ;; esac
			printf '\tIdentityFile %s\n' "$pub"
			echo "	IdentitiesOnly yes"
		} >>"$SSH_CONF"
		aliases="$aliases $alias"
	done <<-EOF
		$(printf '%s\n' "$1" | tr ',' '\n')
	EOF
	if [ -f /etc/ssh/ssh_config ] && ! grep -Eqs '^[[:space:]]*Include[[:space:]].*ssh_config\.d/' /etc/ssh/ssh_config; then
		echo "ssh-agent: warning: /etc/ssh/ssh_config has no Include for ssh_config.d, so $SSH_CONF will be ignored" >&2
	fi
	echo "ssh-agent: ssh aliases:$aliases"
}
write_identities "$IDENTITIES"

echo "ssh-agent: installed"
